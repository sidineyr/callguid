def build_alphabet(add):
    for collection in (LOWER,UPPER,NUMBERS):
        for ch,(advance,paths) in collection.items():add(ch,glyph(paths),advance)

def poly_symbol(strokes):
    pen=TTGlyphPen(None)
    for pts,weight in strokes:
        p=np.array([(x,-y) for x,y in pts],dtype=float)
        # Smooth the existing sign skeletons, using the same rounded nib.
        if len(p)>=8:
            from scipy.interpolate import splprep,splev
            try:
                tck,_=splprep(p.T,s=0,k=min(2,len(p)-1));p=np.array(splev(np.linspace(0,1,max(30,int(np.sum(np.linalg.norm(np.diff(p,axis=0),axis=1))/5))),tck)).T
            except ValueError:pass
        elif len(p)>1 and np.linalg.norm(p[-1]-p[0])>=3:
            dense=[]
            for a,b in zip(p[:-1],p[1:]):
                dense.extend(a+(b-a)*t for t in np.linspace(0,1,max(3,int(np.linalg.norm(b-a)/4)),endpoint=False))
            p=np.vstack([dense,p[-1]])
        if len(p)==2 and np.linalg.norm(p[1]-p[0])<3:
            cx,cy=p.mean(0);theta=np.linspace(0,2*np.pi,24,endpoint=False)
            circle=np.column_stack([cx+18*np.cos(theta)-SLANT*(cy+18*np.sin(theta)),-cy-18*np.sin(theta)])
            smooth_contour(pen,circle[::-1]);continue
        stroke(pen,p,constant=24 if weight<30 else 34)
    return pen.glyph()
