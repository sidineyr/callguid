SLANT = .67
HAIRLINE = 12.0
SHADE = 48.0

def sample(path):
    tokens=re.findall(r'[MLCQZ]|[-+]?(?:\d*\.)?\d+',path)
    i=0; current=None; points=[]
    while i<len(tokens):
        cmd=tokens[i];i+=1
        if cmd=='M':
            current=np.array([float(tokens[i]),float(tokens[i+1])]);i+=2
            points.append(current.copy())
        elif cmd=='L':
            end=np.array([float(tokens[i]),float(tokens[i+1])]);i+=2
            n=max(3,int(np.linalg.norm(end-current)/4))
            points.extend(current+(end-current)*t for t in np.linspace(0,1,n)[1:]);current=end
        elif cmd=='C':
            b=np.array([float(x) for x in tokens[i:i+6]]).reshape(3,2);i+=6
            n=max(8,int((np.linalg.norm(b[0]-current)+np.linalg.norm(b[1]-b[0])+np.linalg.norm(b[2]-b[1]))/4))
            a=current.copy()
            for t in np.linspace(0,1,n)[1:]:points.append((1-t)**3*a+3*(1-t)**2*t*b[0]+3*(1-t)*t*t*b[1]+t**3*b[2])
            current=b[2]
        else: raise ValueError(cmd)
    a=np.asarray(points)
    return a[np.r_[True,np.linalg.norm(np.diff(a,axis=0),axis=1)>.01]]

def smooth_contour(pen,pts):
    # Quadratic B-spline: every join has a shared tangent.
    pts=np.asarray(pts); mid=(pts+np.roll(pts,-1,axis=0))/2
    pen.moveTo(tuple(mid[-1]))
    for p,m in zip(pts,mid):pen.qCurveTo(tuple(p),tuple(m))
    pen.closePath()

def stroke(pen,p,constant=None):
    p=np.asarray(p,dtype=float)
    if len(p)<2:return
    tangent=np.gradient(p,axis=0)
    tangent/=np.maximum(np.linalg.norm(tangent,axis=1)[:,None],.001)
    if constant is None:
        # Downward motion loads the nib; upward motion releases it.
        load=np.clip((tangent[:,1]+.15)/1.15,0,1)
        load=load*load*(3-2*load)
        width=HAIRLINE+(SHADE-HAIRLINE)*load
        width=gaussian_filter1d(width,2)
    else: width=np.full(len(p),constant,dtype=float)
    # Rounded, modestly tapered entry and lift; no blunt polygon terminals.
    arc=np.r_[0,np.cumsum(np.linalg.norm(np.diff(p,axis=0),axis=1))]
    taper=np.minimum(np.minimum(arc,arc[-1]-arc)/35,1)
    width*=.58+.42*np.clip(taper,0,1)
    normal=np.column_stack([-tangent[:,1],tangent[:,0]])
    r=width/2
    left=p+normal*r[:,None];right=p-normal*r[:,None]
    end=[];start=[]
    for theta in np.linspace(0,np.pi,9)[1:-1]:
        end.append(p[-1]+r[-1]*(normal[-1]*np.cos(theta)+tangent[-1]*np.sin(theta)))
        start.append(p[0]+r[0]*(-normal[0]*np.cos(theta)-tangent[0]*np.sin(theta)))
    outline=np.vstack([left,end,right[::-1],start])
    # Transform the complete nib envelope, preserving the specimen's inclination.
    outline[:,0]-=SLANT*outline[:,1]
    outline[:,1]*=-1
    # Consistent winding makes overlapping strokes fill without white seams.
    area=np.sum(outline[:,0]*np.roll(outline[:,1],-1)-np.roll(outline[:,0],-1)*outline[:,1])
    if area>0:outline=outline[::-1]
    smooth_contour(pen,outline)

def glyph(paths):
    pen=TTGlyphPen(None)
    for path in paths:
        if isinstance(path,tuple):
            path,weight=path;stroke(pen,sample(path),weight)
        else:stroke(pen,sample(path))
    return pen.glyph()

